export function getEmergencyNumbers(countryCode) {
  const code = countryCode?.toUpperCase?.();
  const numbers = code ? EMERGENCY_BY_COUNTRY[code] : null;
  return numbers?.length ? numbers : null;
}

export function getEmergencyText(countryCode) {
  const numbers = getEmergencyNumbers(countryCode);
  if (!numbers) {
    return 'Use local emergency services';
  }

  return numbers.join(' / ');
}

export function getEmergencyDialNumber(countryCode) {
  const numbers = getEmergencyNumbers(countryCode);
  return numbers?.[0] ?? null;
}

export function getFindaHelplineUrl(countryCode) {
  const code = countryCode?.toLowerCase?.();
  return code ? `https://findahelpline.com/countries/${code}` : 'https://findahelpline.com/';
}
